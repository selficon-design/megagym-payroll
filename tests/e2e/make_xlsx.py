def make(path, rows, formula=False):
    wb = openpyxl.Workbook(); ws = wb.active; ws.title = "Ερωτήσεις"; ws.append(COLS)
    for r in rows: ws.append(r)
    if formula: ws["L3"] = "=1+1"
    wb.save(path)
