def athens_local(delta_min):
    # ώρα Ελλάδας ως τιμή datetime-local (UTC+2 τον Νοέμβριο)
    t = datetime.datetime.now(datetime.UTC).replace(tzinfo=None) + datetime.timedelta(hours=2, minutes=delta_min)
    return t.strftime("%Y-%m-%dT%H:%M")
